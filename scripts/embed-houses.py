#!/usr/bin/env python3
"""Embeds walk/houses.js (the house kit, composer and ShardForge designs) into walk/index.html between the
HOUSES-JS markers, so Walk stays one self-contained page. Run after editing houses.js: python3 scripts/embed-houses.py"""
import pathlib, re
root = pathlib.Path(__file__).resolve().parent.parent
js = (root / "walk/houses.js").read_text()
page = root / "walk/index.html"
html = page.read_text()
block = f"<!-- HOUSES-JS (generated by scripts/embed-houses.py from walk/houses.js) -->\n<script>\n{js}\n</script>\n<!-- /HOUSES-JS -->"
if "<!-- HOUSES-JS" in html:
    html = re.sub(r"<!-- HOUSES-JS.*?<!-- /HOUSES-JS -->", lambda m: block, html, flags=re.S)
else:
    html = html.replace("<!-- /TERRAIN-DATA -->", "<!-- /TERRAIN-DATA -->\n" + block, 1)
# The ServUO import script, for packages made in Walk without a server.
cs = (root / "servuo/ShardForgeImport.cs").read_text().replace("</script", "<\\/script")
sblock = f'<!-- SERVUO-SCRIPT (generated by scripts/embed-houses.py from servuo/ShardForgeImport.cs) -->\n<script type="text/plain" id="servuoScript">\n{cs}\n</script>\n<!-- /SERVUO-SCRIPT -->'
if "<!-- SERVUO-SCRIPT" in html:
    html = re.sub(r"<!-- SERVUO-SCRIPT.*?<!-- /SERVUO-SCRIPT -->", lambda m: sblock, html, flags=re.S)
else:
    html = html.replace("<!-- /HOUSES-JS -->", "<!-- /HOUSES-JS -->\n" + sblock, 1)
page.write_text(html)
print(f"embedded houses.js ({len(js):,} bytes) and ShardForgeImport.cs ({len(cs):,} bytes)")
