#!/usr/bin/env python3
"""Embeds the terrain blend table (src/ShardForge.Core/Terrain/transitions.json, filtered exactly like
TransitionTable.Pick) and the pure tiles into walk/index.html, between the TERRAIN-DATA markers.
Run after mining new transitions: python3 scripts/embed-terrain.py"""
import json, re, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
src = json.loads((root / "src/ShardForge.Core/Terrain/transitions.json").read_text())
cs = (root / "src/ShardForge.Core/Terrain/TerrainClasses.cs").read_text()
pure = {k: [int(t, 16) for t in re.findall(r"0x([0-9A-Fa-f]+)", v)] for k, v in re.findall(r'\["(\w+)"\] = \[([^\]]*)\]', cs)}
pairs = {}
for key, pats in src["pairs"].items():
    out = {}
    for p, cands in pats.items():
        usable = [c for c in cands if c.get("colorError") is None or c["colorError"] <= 25]
        if not usable: continue
        floor = max(0.75, max(c["confidence"] for c in usable) - 0.15)
        keep = [[c["tile"], c["count"]] for c in usable if c["confidence"] >= floor]
        if keep: out[p] = keep
    if out: pairs[key] = out
data = json.dumps({"pure": pure, "pairs": pairs}, separators=(",", ":"))
page = root / "walk/index.html"
html = page.read_text()
block = f"<!-- TERRAIN-DATA (generated by scripts/embed-terrain.py) -->\n<script type=\"application/json\" id=\"terrainData\">{data}</script>\n<!-- /TERRAIN-DATA -->"
if "<!-- TERRAIN-DATA" in html:
    html = re.sub(r"<!-- TERRAIN-DATA.*?<!-- /TERRAIN-DATA -->", lambda m: block, html, flags=re.S)
else:
    html = html.replace("<script>", block + "\n<script>", 1)
page.write_text(html)
print(f"embedded {len(data):,} bytes: {len(pairs)} pairs, {len(pure)} terrains")
